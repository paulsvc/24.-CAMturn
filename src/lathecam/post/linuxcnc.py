from __future__ import annotations

from typing import Any, Sequence

from lathecam.cam.commands import MotionCmd
from lathecam.post.base_post import BasePostProcessor


class LinuxCNCPostProcessor(BasePostProcessor):
    """Post-processor generating LinuxCNC-compliant lathe G-code (.ngc).
    
    Adheres strictly to LinuxCNC lathe standards:
    - G18 ZX plane selection
    - G7 Diameter Mode vs G8 Radius Mode
    - Strict G7 / G18 Arc Rule: X coordinates doubled in G7, but I and K arc center offsets
      are strictly unscaled radius/distance values.
    - Tool change: M6 T{tool} G43
    - CSS: G96 D{max_rpm} S{css} M3 (Never Fanuc G50)
    - Constant RPM: G97 S{rpm} M3
    - Canned cycles: G76 lathe threading and G83 peck drilling.
    """

    def __init__(self, is_diameter_mode: bool = True) -> None:
        super().__init__(is_diameter_mode=is_diameter_mode)

    def _fmt(self, val: float) -> str:
        """Formats a float to 3 decimal places without unnecessary trailing zero noise."""
        return f"{val:.3f}"

    def export(
        self,
        commands: Sequence[MotionCmd],
        metadata: dict[str, Any] | None = None,
    ) -> str:
        meta = metadata or {}
        lines: list[str] = []

        # 1. Preamble
        lines.append("%")
        comment_hdr = meta.get("program_name", "Generated by LatheCAM for LinuxCNC")
        lines.append(f"({comment_hdr})")

        mode_code = "G7" if self.is_diameter_mode else "G8"
        lines.append(f"G18 G21 G40 G49 G80 G90 G95 {mode_code}")

        # Active initial tool if specified in metadata
        initial_tool = meta.get("tool_id")
        if initial_tool is not None:
            lines.append(f"T{int(initial_tool)} M6 G43")

        # Initial spindle command if in metadata
        css_speed = meta.get("css_m_min")
        max_rpm = meta.get("max_rpm", 2500)
        rpm = meta.get("rpm")
        if css_speed is not None:
            lines.append(f"G96 D{int(max_rpm)} S{int(css_speed)} M3")
        elif rpm is not None:
            lines.append(f"G97 S{int(rpm)} M3")

        # 2. Iterate through motion commands
        x_scale = 2.0 if self.is_diameter_mode else 1.0
        curr_x_rad: float | None = None
        curr_z: float | None = None
        last_mode: str | None = None

        for cmd in commands:
            if cmd.mode == "COMMENT":
                text = cmd.raw_params.get("comment", "") if cmd.raw_params else ""
                lines.append(f"({text})")
                continue

            if cmd.mode == "TOOL_CHANGE":
                t_id = cmd.raw_params.get("tool_id", 1) if cmd.raw_params else 1
                lines.append(f"T{int(t_id)} M6 G43")
                last_mode = None
                continue

            if cmd.mode == "SPINDLE_CSS":
                params = cmd.raw_params or {}
                d_rpm = int(params.get("max_rpm", 2500))
                s_css = int(params.get("css_m_min", 200))
                lines.append(f"G96 D{d_rpm} S{s_css} M3")
                continue

            if cmd.mode == "SPINDLE_RPM":
                params = cmd.raw_params or {}
                s_rpm = int(params.get("rpm", 1000))
                lines.append(f"G97 S{s_rpm} M3")
                continue

            if cmd.mode in ("G0", "G1"):
                next_x_rad = round(cmd.x * x_scale, 3) / x_scale if cmd.x is not None else curr_x_rad
                next_z = round(cmd.z, 3) if cmd.z is not None else curr_z
                if (
                    cmd.mode == "G0"
                    and last_mode == "G0"
                    and curr_x_rad is not None
                    and curr_z is not None
                    and next_x_rad is not None
                    and next_z is not None
                    and abs(next_x_rad - curr_x_rad) < 1e-6
                    and abs(next_z - curr_z) < 1e-6
                ):
                    continue

                parts = [cmd.mode]
                if cmd.x is not None:
                    parts.append(f"X{self._fmt(cmd.x * x_scale)}")
                if cmd.z is not None:
                    parts.append(f"Z{self._fmt(cmd.z)}")
                if cmd.f is not None and cmd.mode == "G1":
                    parts.append(f"F{self._fmt(cmd.f)}")
                lines.append(" ".join(parts))
                curr_x_rad = next_x_rad
                curr_z = next_z
                last_mode = cmd.mode
                continue

            if cmd.mode in ("G2", "G3"):
                next_x_rad = round(cmd.x * x_scale, 3) / x_scale if cmd.x is not None else curr_x_rad
                next_z = round(cmd.z, 3) if cmd.z is not None else curr_z
                i_val = cmd.i
                k_val = cmd.k
                if (
                    curr_x_rad is not None
                    and curr_z is not None
                    and next_x_rad is not None
                    and next_z is not None
                    and i_val is not None
                    and k_val is not None
                ):
                    from lathecam.cad.geometry import _project_center_to_bisector
                    import math
                    raw_c = (curr_z + k_val, curr_x_rad + i_val)
                    raw_r = math.hypot(k_val, i_val)
                    exact_c, _ = _project_center_to_bisector((curr_z, curr_x_rad), (next_z, next_x_rad), raw_c, raw_r)
                    k_val = exact_c[0] - curr_z
                    i_val = exact_c[1] - curr_x_rad

                parts = [cmd.mode]
                if cmd.x is not None:
                    parts.append(f"X{self._fmt(cmd.x * x_scale)}")
                if cmd.z is not None:
                    parts.append(f"Z{self._fmt(cmd.z)}")
                # CRITICAL: In LinuxCNC G18, I is X center offset and K is Z center offset.
                # Both I and K are ALWAYS radius/distance offsets, NEVER scaled by 2.0 in G7!
                if i_val is not None:
                    parts.append(f"I{self._fmt(i_val)}")
                if k_val is not None:
                    parts.append(f"K{self._fmt(k_val)}")
                if cmd.f is not None:
                    parts.append(f"F{self._fmt(cmd.f)}")
                lines.append(" ".join(parts))
                curr_x_rad = next_x_rad
                curr_z = next_z
                last_mode = cmd.mode
                continue

            if cmd.mode in ("G41", "G42", "G40"):
                parts = [cmd.mode]
                if cmd.x is not None:
                    parts.append(f"X{self._fmt(cmd.x * x_scale)}")
                    curr_x_rad = round(cmd.x * x_scale, 3) / x_scale
                if cmd.z is not None:
                    parts.append(f"Z{self._fmt(cmd.z)}")
                    curr_z = round(cmd.z, 3)
                if cmd.f is not None and cmd.mode != "G40":
                    parts.append(f"F{self._fmt(cmd.f)}")
                lines.append(" ".join(parts))
                last_mode = cmd.mode
                continue

            if cmd.mode == "G76":
                # LinuxCNC G76 Canned Threading Cycle
                # G76 P- Z- I- J- K- R- Q- H- E- L-
                p = cmd.raw_params or {}
                p_pitch = p.get("p", 1.5)
                z_end = p.get("z", cmd.z if cmd.z is not None else -10.0)
                i_off = p.get("i", -0.2)
                j_first = p.get("j", 0.2)
                k_depth = p.get("k", 1.0)
                r_deg = p.get("r", 1.0)
                q_angle = p.get("q", 29.5)
                h_spring = int(p.get("h", 1))
                e_taper = p.get("e", 0.0)
                l_type = int(p.get("l", 0))

                line = (
                    f"G76 P{self._fmt(p_pitch)} Z{self._fmt(z_end)} "
                    f"I{self._fmt(i_off)} J{self._fmt(j_first)} K{self._fmt(k_depth)} "
                    f"R{self._fmt(r_deg)} Q{self._fmt(q_angle)} H{h_spring} "
                    f"E{self._fmt(e_taper)} L{l_type}"
                )
                lines.append(line)
                continue

            if cmd.mode in ("G83", "G73"):
                # Canned drilling cycle
                p = cmd.raw_params or {}
                z_depth = cmd.z if cmd.z is not None else -10.0
                r_plane = p.get("r_plane", 1.0)
                q_peck = p.get("peck_q", 2.0)
                feed = cmd.f if cmd.f is not None else 0.12

                line = f"{cmd.mode} X0.000 Z{self._fmt(z_depth)} R{self._fmt(r_plane)} Q{self._fmt(q_peck)} F{self._fmt(feed)}"
                lines.append(line)
                continue

            if cmd.mode == "G80":
                lines.append("G80")
                continue

            if cmd.mode == "G33":
                # Spindle-synchronized motion
                parts = ["G33"]
                if cmd.x is not None:
                    parts.append(f"X{self._fmt(cmd.x * x_scale)}")
                if cmd.z is not None:
                    parts.append(f"Z{self._fmt(cmd.z)}")
                if cmd.k is not None:
                    parts.append(f"K{self._fmt(cmd.k)}")
                lines.append(" ".join(parts))
                continue

        # 3. Postamble / Footer
        lines.append("M5")
        lines.append("M9")
        lines.append("M30")
        lines.append("%")

        return "\n".join(lines) + "\n"
